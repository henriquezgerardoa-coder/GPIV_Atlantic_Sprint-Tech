SET codigo = 'LV' || LPAD(TRIM(LEADING '0' FROM REPLACE(codigo, 'PV-', ''))::INTEGER::TEXT, 3, '0'),
    zona   = 'PARQUE_VIEJO'
WHERE codigo LIKE 'PV-%'
  AND REPLACE(codigo, 'PV-', '')::INTEGER BETWEEN 1 AND 60;

